// WriteYAML writes the draft park file. The output is a starting point for hand editing: node
// attributes the simulation needs (capacity, appeal, schedules) and the park-wide sections are
// left for the author.
func (d *Draft) WriteYAML(w io.Writer, extract string) error {
	var b strings.Builder
	p := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	p("# %s — park config draft, schema 1.0\n", d.Name)
	p("# Generated by `ridesim osm-import` from %s (OSM base %s). Review, then edit by hand;\n", extract, d.Timestamp)
	p("# the importer never rewrites an existing file.\n")
	p("# Geometry © OpenStreetMap contributors, ODbL 1.0 (https://www.openstreetmap.org/copyright).\n")
	p("# x, y: feet east and south of the park's north-west corner (%.6f, %.6f) [osm].\n", d.Origin.Lat, d.Origin.Lon)
	p("# Edge lengths follow the OSM path geometry [osm]; widths are defaults by path type [assumed].\n\n")
	p("schema_version: \"1.0\"\n\npark:\n  id: %s\n  walking_mode: congestion\n\nnodes:\n", d.ParkID)
	kind := ""
	for _, n := range d.Nodes {
		if n.Kind != kind {
			kind = n.Kind
			p("  # %s\n", kind)
		}
		p("  - { id: %s, kind: %s, x: %s, y: %s }", n.ID, n.Kind, ft(n.P.X), ft(n.P.Y))
		var c []string
		if len(n.OSM) > 0 {
			c = append(c, "[osm] "+strings.Join(n.OSM, " "))
		} else {
			c = append(c, "[osm]")
		}
		if n.Name != "" {
			c = append(c, n.Name)
		}
		if n.Land != "" {
			c = append(c, n.Land)
		}
		if len(n.MapNo) > 0 {
			c = append(c, "map "+joinInts(n.MapNo))
		}
		p("   # %s\n", strings.Join(c, " · "))
	}
	p("\nedges:                               # bidirectional\n")
	for _, e := range d.Edges {
		p("  - { id: %s, from: %s, to: %s, length_ft: %s, width_ft: %s }", e.ID, e.From, e.To, ft(e.LengthFt), ft(e.WidthFt))
		if e.Class == "spur" {
			p("   # length [osm] attraction to walkway, width [assumed] as the walkway it joins\n")
		} else {
			p("   # length [osm], width [assumed] %s\n", e.Class)
		}
	}
	if len(d.Notes) > 0 {
		p("\n# Import notes:\n")
		for _, n := range d.Notes {
			p("#   %s\n", n)
		}
	}
	_, err := io.WriteString(w, b.String())
	return err
}

// WriteSVG writes a review map: walkways, junctions and labelled nodes, in park feet.
func (d *Draft) WriteSVG(w io.Writer) error {
	pos := map[string]Pt{}
	minX, minY, maxX, maxY := math.Inf(1), math.Inf(1), math.Inf(-1), math.Inf(-1)
	for _, n := range d.Nodes {
		pos[n.ID] = n.P
		minX, minY = math.Min(minX, n.P.X), math.Min(minY, n.P.Y)
		maxX, maxY = math.Max(maxX, n.P.X), math.Max(maxY, n.P.Y)
	}
	var b strings.Builder
	p := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	pad := 120.0
	p(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="%s %s %s %s" font-family="sans-serif">`+"\n",
		ft(minX-pad), ft(minY-pad), ft(maxX-minX+2*pad), ft(maxY-minY+2*pad))
	p(`<rect x="%s" y="%s" width="100%%" height="100%%" fill="#fff"/>`+"\n", ft(minX-pad), ft(minY-pad))
	for _, s := range d.Dropped {
		p(`<line x1="%s" y1="%s" x2="%s" y2="%s" stroke="#f90" stroke-width="3"/>`+"\n", ft(s[0].X), ft(s[0].Y), ft(s[1].X), ft(s[1].Y))
	}
	for _, e := range d.Edges {
		a, c := pos[e.From], pos[e.To]
		color := "#888"
		if e.Class == "spur" {
			color = "#d33"
		}
		p(`<line x1="%s" y1="%s" x2="%s" y2="%s" stroke="%s" stroke-width="%s"/>`+"\n", ft(a.X), ft(a.Y), ft(c.X), ft(c.Y), color, ft(math.Max(2, e.WidthFt/4)))
	}
	for _, n := range d.Nodes {
		if n.Kind == "junction" {
			p(`<circle cx="%s" cy="%s" r="5" fill="#333"/>`+"\n", ft(n.P.X), ft(n.P.Y))
			continue
		}
		p(`<circle cx="%s" cy="%s" r="12" fill="#1a7"/><text x="%s" y="%s" font-size="22">%s</text>`+"\n",
			ft(n.P.X), ft(n.P.Y), ft(n.P.X+14), ft(n.P.Y-8), n.ID)
	}
	p("</svg>\n")
	_, err := io.WriteString(w, b.String())
	return err
}

func ft(v float64) string { return strconv.FormatFloat(math.Round(v), 'f', 0, 64) }

func joinInts(xs []int) string {
	s := make([]string, len(xs))
	for i, x := range xs {
		s[i] = strconv.Itoa(x)
	}
	return strings.Join(s, ", ")
}
